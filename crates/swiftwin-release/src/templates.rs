//! Files generated for the cloud Mac: the GitHub Actions workflow, an
//! XcodeGen spec built from `swiftwin.toml`, and ExportOptions.plist.
//!
//! On the Mac, real Xcode tools are available, so the build is a normal
//! `xcodebuild archive` + `-exportArchive` with `destination=upload`
//! (uploads to App Store Connect / TestFlight), using automatic signing
//! authenticated by the App Store Connect API key.

use swiftwin_builder::Project;

pub const BRANCH: &str = "swiftwin/release";
pub const WORKFLOW_PATH: &str = ".github/workflows/swiftwin-release.yml";
pub const XCODEGEN_PATH: &str = "swiftwin-xcodegen.yml";
pub const EXPORT_OPTIONS_PATH: &str = "ExportOptions.plist";

#[derive(Debug, Clone)]
pub struct ReleaseSettings {
    /// GitHub-hosted macOS image with Xcode 26 (`macos-26`).
    pub runs_on: String,
    /// Prefix of the Xcode app to select, e.g. "Xcode_26".
    pub xcode: String,
}

impl Default for ReleaseSettings {
    fn default() -> Self {
        ReleaseSettings { runs_on: "macos-26".into(), xcode: "Xcode_26".into() }
    }
}

fn yaml_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

pub fn workflow(project: &Project, s: &ReleaseSettings) -> String {
    let scheme = project.executable();
    format!(
        r#"# Generated by SwiftWin. Builds the app with Xcode on a macOS runner and uploads it to TestFlight.
name: swiftwin-release
on:
  push:
    branches: ["{BRANCH}"]
  workflow_dispatch: {{}}
# The job only reads the repository; the App Store Connect key is given only to the steps that use it.
permissions:
  contents: read
jobs:
  testflight:
    runs-on: {runs_on}
    timeout-minutes: 60
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4
        with:
          persist-credentials: false
      - name: Select Xcode
        run: |
          XCODE=$(ls -d /Applications/{xcode}*.app | sort -V | tail -1)
          echo "Using $XCODE"
          sudo xcode-select -s "$XCODE"
          xcodebuild -version
      - name: Install XcodeGen
        run: brew install xcodegen
      - name: Generate Xcode project
        run: xcodegen generate --spec {XCODEGEN_PATH}
      - name: App Store Connect API key
        env:
          ASC_KEY_ID: ${{{{ secrets.SWIFTWIN_ASC_KEY_ID }}}}
          ASC_KEY_P8_BASE64: ${{{{ secrets.SWIFTWIN_ASC_KEY_P8 }}}}
        run: |
          mkdir -p "$RUNNER_TEMP/keys"
          echo "$ASC_KEY_P8_BASE64" | base64 --decode > "$RUNNER_TEMP/keys/AuthKey_$ASC_KEY_ID.p8"
      - name: Archive
        env:
          ASC_KEY_ID: ${{{{ secrets.SWIFTWIN_ASC_KEY_ID }}}}
          ASC_ISSUER_ID: ${{{{ secrets.SWIFTWIN_ASC_ISSUER_ID }}}}
          TEAM_ID: ${{{{ secrets.SWIFTWIN_TEAM_ID }}}}
        run: |
          xcodebuild archive \
            -project {scheme}.xcodeproj -scheme {scheme} -configuration Release \
            -destination 'generic/platform=iOS' -archivePath "$RUNNER_TEMP/{scheme}.xcarchive" \
            -allowProvisioningUpdates \
            -authenticationKeyPath "$RUNNER_TEMP/keys/AuthKey_$ASC_KEY_ID.p8" \
            -authenticationKeyID "$ASC_KEY_ID" -authenticationKeyIssuerID "$ASC_ISSUER_ID" \
            DEVELOPMENT_TEAM="$TEAM_ID" CODE_SIGN_STYLE=Automatic \
            CURRENT_PROJECT_VERSION=${{{{ github.run_number }}}}
      - name: Upload to TestFlight
        env:
          ASC_KEY_ID: ${{{{ secrets.SWIFTWIN_ASC_KEY_ID }}}}
          ASC_ISSUER_ID: ${{{{ secrets.SWIFTWIN_ASC_ISSUER_ID }}}}
          TEAM_ID: ${{{{ secrets.SWIFTWIN_TEAM_ID }}}}
        run: |
          sed -i '' "s/TEAM_ID_PLACEHOLDER/$TEAM_ID/" {EXPORT_OPTIONS_PATH}
          xcodebuild -exportArchive -archivePath "$RUNNER_TEMP/{scheme}.xcarchive" \
            -exportOptionsPlist {EXPORT_OPTIONS_PATH} -exportPath "$RUNNER_TEMP/export" \
            -allowProvisioningUpdates \
            -authenticationKeyPath "$RUNNER_TEMP/keys/AuthKey_$ASC_KEY_ID.p8" \
            -authenticationKeyID "$ASC_KEY_ID" -authenticationKeyIssuerID "$ASC_ISSUER_ID"
      - name: Clean up key
        if: always()
        run: rm -rf "$RUNNER_TEMP/keys"
"#,
        runs_on = s.runs_on,
        xcode = s.xcode,
    )
}

/// XcodeGen project spec (https://github.com/yonaskolb/XcodeGen) mirroring `swiftwin.toml`.
pub fn xcodegen(project: &Project) -> String {
    let a = project.app();
    let name = project.executable();
    let mut props = vec![
        ("CFBundleDisplayName".to_string(), yaml_str(a.display_name.as_deref().unwrap_or(&a.name))),
        ("CFBundleShortVersionString".to_string(), yaml_str(&a.version)),
        ("CFBundleVersion".to_string(), yaml_str("$(CURRENT_PROJECT_VERSION)")),
        ("UILaunchScreen".to_string(), "{}".to_string()),
        ("ITSAppUsesNonExemptEncryption".to_string(), "false".to_string()),
    ];
    let orients: Vec<String> = a
        .orientations
        .iter()
        .filter_map(|o| swiftwin_builder::infoplist::orientation_key(o))
        .map(yaml_str)
        .collect();
    props.push(("UISupportedInterfaceOrientations".into(), format!("[{}]", orients.join(", "))));
    for (k, v) in &project.file.info {
        // Keys are checked by Project::load (letters, digits, `_-.`); quoted anyway.
        props.push((yaml_str(k),serde_json::to_string(&toml_json(v)).unwrap_or_default()));
    }
    let mut sources = vec![format!("      - path: {}", yaml_str(&a.sources))];
    if project.assets_dir().exists() {
        sources.push(format!("      - path: {}", yaml_str(&a.assets)));
    }
    if project.resources_dir().exists() {
        sources.push(format!("      - path: {}\n        buildPhase: resources", yaml_str(&a.resources)));
    }
    let props_yaml: String = props.iter().map(|(k, v)| format!("        {k}: {v}\n")).collect();
    format!(
        r#"# Generated by SwiftWin from swiftwin.toml.
name: {name}
options:
  bundleIdPrefix: {prefix}
  deploymentTarget:
    iOS: "{target}"
targets:
  {name}:
    type: application
    platform: iOS
    sources:
{sources}
    info:
      path: Generated/Info.plist
      properties:
{props_yaml}    settings:
      base:
        PRODUCT_BUNDLE_IDENTIFIER: {bundle}
        PRODUCT_NAME: {name}
        TARGETED_DEVICE_FAMILY: "1"
        ASSETCATALOG_COMPILER_APPICON_NAME: AppIcon
        GENERATE_INFOPLIST_FILE: NO
        SWIFT_VERSION: "5.0"
"#,
        prefix = a.bundle_id.rsplit_once('.').map(|(p, _)| p).unwrap_or(&a.bundle_id),
        target = a.deployment_target,
        sources = sources.join("\n"),
        bundle = a.bundle_id,
    )
}

fn toml_json(v: &swiftwin_builder::project::TomlValue) -> serde_json::Value {
    serde_json::to_value(v).unwrap_or(serde_json::Value::Null)
}

pub fn export_options() -> String {
    r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>method</key><string>app-store-connect</string>
  <key>destination</key><string>upload</string>
  <key>signingStyle</key><string>automatic</string>
  <key>teamID</key><string>TEAM_ID_PLACEHOLDER</string>
  <key>uploadSymbols</key><true/>
  <key>manageAppVersionAndBuildNumber</key><false/>
</dict>
</plist>
"#
    .to_string()
}
