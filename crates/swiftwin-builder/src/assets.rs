//! Asset catalog (`Assets.xcassets`) processing without Apple's `actool`.
//!
//! `actool` (which produces `Assets.car`) only exists on macOS, so SwiftWin
//! compiles the common parts itself:
//!
//! * **AppIcon.appiconset** – the largest image is resized to the iPhone home
//!   screen sizes and written as loose `AppIcon60x60@2x.png` / `@3x.png`,
//!   referenced from `CFBundleIcons > CFBundleIconFiles` in Info.plist.
//! * **\*.imageset** – copied as loose `name.png`, `name@2x.png`, `name@3x.png`
//!   (found by `UIImage(named:)` / `Image("name")` via the bundle).
//! * **\*.colorset** – turned into Swift code: `extension Color { static let brand = ... }`.
//!
//! Limitations are listed in docs/open-questions.md.

use std::path::{Path, PathBuf};

use serde_json::Value;
use swiftwin_core::{Result, SwiftWinError};

#[derive(Debug, Default, Clone)]
pub struct CompiledAssets {
    /// (source, file name in the .app root)
    pub copies: Vec<(PathBuf, String)>,
    /// (png bytes, file name in the .app root)
    pub generated: Vec<(Vec<u8>, String)>,
    /// CFBundleIconFiles entries.
    pub icon_files: Vec<String>,
    /// Swift source to compile with the app (colors), if any.
    pub swift: Option<String>,
    pub warnings: Vec<String>,
}

pub fn compile(catalog: &Path) -> Result<CompiledAssets> {
    let mut out = CompiledAssets::default();
    if !catalog.exists() {
        return Ok(out);
    }
    let mut colors = Vec::new();
    visit(catalog, &mut out, &mut colors)?;
    if !colors.is_empty() {
        let mut s = String::from("// Generated by SwiftWin from the asset catalog. Do not edit.\nimport SwiftUI\n\nextension Color {\n");
        for (name, r, g, b, a) in colors {
            s.push_str(&format!(
                "    static let {} = Color(.sRGB, red: {r:.4}, green: {g:.4}, blue: {b:.4}, opacity: {a:.4})\n",
                swift_ident(&name)
            ));
        }
        s.push_str("}\n");
        out.swift = Some(s);
    }
    Ok(out)
}

type ColorDef = (String, f64, f64, f64, f64);

fn visit(dir: &Path, out: &mut CompiledAssets, colors: &mut Vec<ColorDef>) -> Result<()> {
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)?.flatten().map(|e| e.path()).collect();
    entries.sort();
    for p in entries.into_iter().filter(|p| p.is_dir()) {
        let name = p.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
        match p.extension().and_then(|e| e.to_str()) {
            Some("appiconset") if name == "AppIcon" => app_icon(&p, out)?,
            Some("appiconset") => out.warnings.push(format!("alternate icon set {name} is ignored")),
            Some("imageset") => image_set(&p, &name, out)?,
            Some("colorset") => {
                if name == "AccentColor" {
                    out.warnings.push("AccentColor needs Assets.car; use .tint(...) in SwiftUI instead".into());
                }
                if let Some(c) = color_set(&p)? {
                    colors.push((name, c.0, c.1, c.2, c.3));
                }
            }
            Some(other) => out.warnings.push(format!("asset type .{other} ({name}) is not supported yet")),
            None => visit(&p, out, colors)?, // plain folder (namespace)
        }
    }
    Ok(())
}

fn contents(dir: &Path) -> Result<Value> {
    let f = dir.join("Contents.json");
    let data = std::fs::read(&f).map_err(|e| SwiftWinError::invalid(format!("{}: {e}", f.display())))?;
    serde_json::from_slice(&data).map_err(|e| SwiftWinError::invalid(format!("{}: {e}", f.display())))
}

fn app_icon(dir: &Path, out: &mut CompiledAssets) -> Result<()> {
    let c = contents(dir)?;
    // Pick the biggest image file listed.
    let mut best: Option<(u32, PathBuf)> = None;
    for img in c["images"].as_array().into_iter().flatten() {
        let Some(file) = img["filename"].as_str() else { continue };
        let path = dir.join(file);
        let Ok(data) = std::fs::read(&path) else { continue };
        if let Some((w, _)) = swiftwin_core::png_dimensions(&data) {
            if best.as_ref().is_none_or(|(bw, _)| w > *bw) {
                best = Some((w, path));
            }
        }
    }
    let Some((_, src)) = best else {
        out.warnings.push("AppIcon has no PNG images; the app will have a blank icon".into());
        return Ok(());
    };
    let img = Image::decode(&std::fs::read(src)?)?;
    for (size, suffix) in [(120u32, "@2x"), (180, "@3x")] {
        out.generated.push((img.resize(size, size).encode_rgb(), format!("AppIcon60x60{suffix}.png")));
    }
    out.icon_files.push("AppIcon60x60".into());
    Ok(())
}

fn image_set(dir: &Path, name: &str, out: &mut CompiledAssets) -> Result<()> {
    let c = contents(dir)?;
    for img in c["images"].as_array().into_iter().flatten() {
        let Some(file) = img["filename"].as_str() else { continue };
        let ext = Path::new(file).extension().and_then(|e| e.to_str()).unwrap_or("png");
        let scale = match img["scale"].as_str() {
            Some("2x") => "@2x",
            Some("3x") => "@3x",
            _ => "",
        };
        out.copies.push((dir.join(file), format!("{name}{scale}.{ext}")));
    }
    Ok(())
}

/// Parse a colorset's universal color (sRGB / display-P3 treated as sRGB).
pub fn color_set(dir: &Path) -> Result<Option<(f64, f64, f64, f64)>> {
    let c = contents(dir)?;
    let Some(col) = c["colors"].as_array().and_then(|a| {
        a.iter().find(|c| c["appearances"].is_null()).or_else(|| a.first())
    }) else {
        return Ok(None);
    };
    let comp = &col["color"]["components"];
    let get = |k: &str| component(&comp[k]);
    Ok(Some((get("red"), get("green"), get("blue"), comp.get("alpha").map(component).unwrap_or(1.0))))
}

/// Xcode writes components as "0.478", "0x7A", "122" or numbers.
pub fn component(v: &Value) -> f64 {
    let x = match v {
        Value::Number(n) => n.as_f64().unwrap_or(0.0),
        Value::String(s) => {
            let s = s.trim();
            if let Some(h) = s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
                return i64::from_str_radix(h, 16).map(|v| v as f64 / 255.0).unwrap_or(0.0);
            }
            if s.contains('.') {
                s.parse().unwrap_or(0.0)
            } else {
                let i: f64 = s.parse().unwrap_or(0.0);
                return if i > 1.0 { i / 255.0 } else { i };
            }
        }
        _ => 0.0,
    };
    if x > 1.0 {
        x / 255.0
    } else {
        x
    }
}

pub fn swift_ident(name: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_alphanumeric() {
            if out.is_empty() {
                out.push(if i == 0 { ch.to_ascii_lowercase() } else { ch });
            } else if upper {
                out.push(ch.to_ascii_uppercase());
            } else {
                out.push(ch);
            }
            upper = false;
        } else {
            upper = true;
        }
    }
    if out.is_empty() || out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// Minimal RGBA image for icon resizing.
pub struct Image {
    pub w: u32,
    pub h: u32,
    pub rgba: Vec<u8>,
}

impl Image {
    pub fn decode(data: &[u8]) -> Result<Image> {
        let mut dec = png::Decoder::new(data);
        dec.set_transformations(png::Transformations::EXPAND | png::Transformations::STRIP_16);
        let mut r = dec.read_info().map_err(|e| SwiftWinError::invalid(format!("PNG: {e}")))?;
        let mut buf = vec![0; r.output_buffer_size()];
        let info = r.next_frame(&mut buf).map_err(|e| SwiftWinError::invalid(format!("PNG: {e}")))?;
        let px = &buf[..info.buffer_size()];
        let rgba: Vec<u8> = match info.color_type {
            png::ColorType::Rgba => px.to_vec(),
            png::ColorType::Rgb => px.chunks(3).flat_map(|c| [c[0], c[1], c[2], 255]).collect(),
            png::ColorType::GrayscaleAlpha => px.chunks(2).flat_map(|c| [c[0], c[0], c[0], c[1]]).collect(),
            png::ColorType::Grayscale => px.iter().flat_map(|&g| [g, g, g, 255]).collect(),
            png::ColorType::Indexed => return Err(SwiftWinError::invalid("PNG: unexpanded palette")),
        };
        Ok(Image { w: info.width, h: info.height, rgba })
    }

    /// Area-averaging resize (good for downscaling icons).
    pub fn resize(&self, nw: u32, nh: u32) -> Image {
        let mut out = vec![0u8; (nw * nh * 4) as usize];
        let (sx, sy) = (self.w as f64 / nw as f64, self.h as f64 / nh as f64);
        for y in 0..nh {
            for x in 0..nw {
                let (x0, x1) = ((x as f64 * sx) as u32, (((x + 1) as f64 * sx).ceil() as u32).min(self.w).max(1));
                let (y0, y1) = ((y as f64 * sy) as u32, (((y + 1) as f64 * sy).ceil() as u32).min(self.h).max(1));
                let mut acc = [0u64; 4];
                let mut n = 0u64;
                for yy in y0..y1.max(y0 + 1) {
                    for xx in x0..x1.max(x0 + 1) {
                        let i = ((yy.min(self.h - 1) * self.w + xx.min(self.w - 1)) * 4) as usize;
                        for (k, a) in acc.iter_mut().enumerate() {
                            *a += self.rgba[i + k] as u64;
                        }
                        n += 1;
                    }
                }
                let o = ((y * nw + x) * 4) as usize;
                for k in 0..4 {
                    out[o + k] = (acc[k] / n.max(1)) as u8;
                }
            }
        }
        Image { w: nw, h: nh, rgba: out }
    }

    /// Encode as opaque RGB (alpha composited over white), as iOS icons should be.
    pub fn encode_rgb(&self) -> Vec<u8> {
        let rgb: Vec<u8> = self
            .rgba
            .chunks(4)
            .flat_map(|p| {
                let a = p[3] as u32;
                [0, 1, 2].map(|k| ((p[k] as u32 * a + 255 * (255 - a)) / 255) as u8)
            })
            .collect();
        encode_png(self.w, self.h, &rgb, png::ColorType::Rgb)
    }
}

pub fn encode_png(w: u32, h: u32, data: &[u8], color: png::ColorType) -> Vec<u8> {
    let mut out = Vec::new();
    {
        let mut e = png::Encoder::new(&mut out, w, h);
        e.set_color(color);
        e.set_depth(png::BitDepth::Eight);
        let mut wr = e.write_header().expect("png header");
        wr.write_image_data(data).expect("png data");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn components_in_all_xcode_formats() {
        assert!((component(&json!("0.478")) - 0.478).abs() < 1e-9);
        assert!((component(&json!("0x7A")) - 122.0 / 255.0).abs() < 1e-9);
        assert!((component(&json!("255")) - 1.0).abs() < 1e-9);
        assert!((component(&json!(0.5)) - 0.5).abs() < 1e-9);
        assert_eq!(component(&json!("1")), 1.0);
    }

    #[test]
    fn identifiers() {
        assert_eq!(swift_ident("Brand"), "brand");
        assert_eq!(swift_ident("brand-primary color"), "brandPrimaryColor");
        assert_eq!(swift_ident("2fast"), "_2fast");
    }

    #[test]
    fn resize_averages() {
        let img = Image { w: 2, h: 2, rgba: vec![0, 0, 0, 255, 255, 255, 255, 255, 0, 0, 0, 255, 255, 255, 255, 255] };
        let r = img.resize(1, 1);
        assert_eq!(&r.rgba, &[127, 127, 127, 255]);
        let png = r.encode_rgb();
        assert_eq!(swiftwin_core::png_dimensions(&png), Some((1, 1)));
        assert_eq!(Image::decode(&png).unwrap().rgba, vec![127, 127, 127, 255]);
    }
}
